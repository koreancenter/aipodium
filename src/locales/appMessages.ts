export type AppMessageId = keyof typeof APP_MESSAGES.ko;

export function formatMessage(template: string, args: ReadonlyArray<string | number>): string {
  return template.replace(/\{(\d+)\}/g, (_, index) => String(args[Number(index)] ?? ''));
}

/** Resolves a message in the active UI language at call time, so it is safe inside long-lived callbacks. */
export function translateMessage(id: AppMessageId, ...args: Array<string | number>): string {
  return formatMessage(APP_MESSAGES[getActiveLanguage()][id], args);
}

export function getAppMessages(language: 'ko' | 'en') {
  return APP_MESSAGES[language];
}
